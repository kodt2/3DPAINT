#!/usr/bin/env node
/**
 * Copies the GLB decoders bundled with three.js into public/ (step 3c.5).
 *
 * The viewer decodes Draco/Meshopt/KTX2 with LOCAL decoder files (no CDN,
 * ADR 0014):
 *   public/assets/decoders/three-<version>/
 *     draco/  draco_wasm_wrapper.js, draco_decoder.wasm   (DRACOLoader)
 *     basis/  basis_transcoder.js, basis_transcoder.wasm  (KTX2Loader)
 *
 * Meshopt needs no files: three r187's meshopt_decoder.module.js embeds its
 * wasm as base64 and creates workers from a Blob URL.
 *
 * The files are versioned by the three package version (directory name), so
 * a three upgrade changes the URL and browsers pick the fresh decoders
 * (immutable cache, nginx /assets/**). The target directory is gitignored;
 * the script runs on `prebuild` and `predev` (npm lifecycle hooks).
 *
 * The script also writes src/generated/decoder-version.ts — the app code
 * builds the decoder base URL from that constant, so the version lives in
 * exactly one place (three's package.json).
 */
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const frontendRoot = dirname(here);
const threePackagePath = join(frontendRoot, 'node_modules', 'three', 'package.json');

if (!existsSync(threePackagePath)) {
  console.error('[sync-decoders] three is not installed; run `npm ci` first.');
  process.exit(1);
}

const threeVersion = JSON.parse(readFileSync(threePackagePath, 'utf8')).version;
const destRoot = join(frontendRoot, 'public', 'assets', 'decoders', `three-${threeVersion}`);
const versionFile = join(frontendRoot, 'src', 'generated', 'decoder-version.ts');

const files = [
  ['examples/jsm/libs/draco/gltf/draco_wasm_wrapper.js', 'draco/draco_wasm_wrapper.js'],
  ['examples/jsm/libs/draco/gltf/draco_decoder.wasm', 'draco/draco_decoder.wasm'],
  ['examples/jsm/libs/basis/basis_transcoder.js', 'basis/basis_transcoder.js'],
  ['examples/jsm/libs/basis/basis_transcoder.wasm', 'basis/basis_transcoder.wasm'],
];

rmSync(destRoot, { recursive: true, force: true });
for (const [src, dest] of files) {
  const from = join(frontendRoot, 'node_modules', 'three', src);
  if (!existsSync(from)) {
    console.error(`[sync-decoders] missing decoder source: ${src}`);
    process.exit(1);
  }
  const to = join(destRoot, dest);
  mkdirSync(dirname(to), { recursive: true });
  cpSync(from, to);
}

mkdirSync(dirname(versionFile), { recursive: true });
writeFileSync(
  versionFile,
  [
    '// GENERATED by scripts/sync-decoders.mjs — do not edit (step 3c.5).',
    `export const DECODER_THREE_VERSION = '${threeVersion}';`,
    '',
  ].join('\n'),
);

console.log(`[sync-decoders] three@${threeVersion} decoders -> ${relative(frontendRoot, destRoot)}/`);
console.log(`[sync-decoders] version constant -> ${relative(frontendRoot, versionFile)}`);
