#!/bin/sh
# 3DPAINT step H (ADR 0016): generate /config/Caddyfile from the
# environment, then exec Caddy with it.
#
# Environment:
#   MAIN_HOST   host part of PUBLIC_ORIGIN (no scheme/port): site -> gateway
#   S3_HOST     host part of PUBLIC_S3_ENDPOINT: S3 site -> storage
#   TLS_MODE    lan (default: Caddy internal CA, no HSTS)
#               prod (Let's Encrypt, HSTS enabled)
#   ACME_EMAIL  required for TLS_MODE=prod
#
# Container ports are fixed: 443 (site; in prod mode S3 as well, SNI-based),
# 9443 (S3, lan mode), 80 (ACME / redirect, prod mode).
# The host-side ports are mapped in infra/compose.https.yml.
set -eu

: "${MAIN_HOST:?MAIN_HOST is required (host part of PUBLIC_ORIGIN)}"
: "${S3_HOST:?S3_HOST is required (host part of PUBLIC_S3_ENDPOINT)}"
TLS_MODE="${TLS_MODE:-lan}"
CONFIG=/config/Caddyfile

case "$TLS_MODE" in
lan)
    cat > "$CONFIG" <<EOF
# Generated by entrypoint.sh on every start — do not edit by hand.
# TLS_MODE=lan: Caddy internal CA (tls internal), no HSTS (ADR 0016).
https://${MAIN_HOST}:443 {
    tls internal
    reverse_proxy gateway:8080
}

https://${S3_HOST}:9443 {
    tls internal
    reverse_proxy storage:9000
}
EOF
    ;;
prod)
    : "${ACME_EMAIL:?ACME_EMAIL is required for TLS_MODE=prod}"
    cat > "$CONFIG" <<EOF
# Generated by entrypoint.sh on every start — do not edit by hand.
# TLS_MODE=prod: Let's Encrypt (HTTP-01 on :80), HSTS enabled (ADR 0016).
{
    email ${ACME_EMAIL}
}

https://${MAIN_HOST} {
    reverse_proxy gateway:8080
    header Strict-Transport-Security "max-age=63072000; includeSubDomains"
}

https://${S3_HOST} {
    reverse_proxy storage:9000
    header Strict-Transport-Security "max-age=63072000; includeSubDomains"
}
EOF
    ;;
*)
    echo "caddy entrypoint: unknown TLS_MODE '$TLS_MODE' (expected: lan, prod)" >&2
    exit 1
    ;;
esac

echo "caddy: generated $CONFIG (TLS_MODE=$TLS_MODE, main=$MAIN_HOST, s3=$S3_HOST)" >&2
exec /usr/bin/caddy run --config "$CONFIG"
